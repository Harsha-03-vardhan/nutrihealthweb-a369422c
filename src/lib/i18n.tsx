const dicts: Record<Lang, Dict> = { English: en, Tamil: ta };

export function translate(lang: Lang, key: string): string {
  return dicts[lang]?.[key] ?? en[key] ?? key;
}

/** Returns a translator bound to the persisted language preference. */
export function useT() {
  const lang = useSettings((s) => s.language);
  const t = (key: string, vars?: Record<string, string | number>) => {
    let out = translate(lang, key);
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
    return out;
  };
  /** Translates data-driven content strings (meal names, symptoms, guides…). */
  const tx = (value: string) => translateContent(lang, value);
  return { t, tx, lang };
}

